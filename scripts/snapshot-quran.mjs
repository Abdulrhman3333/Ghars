#!/usr/bin/env node
/**
 * snapshot-quran.mjs — one-time snapshot of the Madani mushaf (QCF v2 pagination)
 * from the Quran.com API v4 into a SQL seed file:
 *
 *   supabase/seed/quran_snapshot.sql   (chapters, quran_verses, quran_words)
 *
 * Run:  npm run snapshot:quran
 * The app NEVER calls quran.com at runtime; this file is the source of truth.
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const API = 'https://api.quran.com/api/v4';
const PAGES = 604;
const WORD_FIELDS = 'code_v2,line_number,location,text_uthmani,char_type_name,v2_page';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'supabase', 'seed');
const outFile = join(outDir, 'quran_snapshot.sql');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchJson(url, tries = 4) {
  let lastErr;
  for (let i = 0; i < tries; i++) {
    try {
      const r = await fetch(url);
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      return await r.json();
    } catch (e) {
      lastErr = e;
      await sleep(500 * 2 ** i);
    }
  }
  throw lastErr;
}

const sql = (s) => `'${String(s).replaceAll("'", "''")}'`;
const num = (n) => (n === null || n === undefined ? 'null' : String(n));

function* batches(arr, size) {
  for (let i = 0; i < arr.length; i += size) yield arr.slice(i, i + size);
}

async function main() {
  console.log('1/2  chapters…');
  const chaptersJ = await fetchJson(`${API}/chapters?language=ar`);
  const chapters = chaptersJ.chapters.map((c) => ({
    id: c.id,
    name_arabic: c.name_arabic,
    name_simple: c.name_simple,
    verses_count: c.verses_count,
    bismillah_pre: c.bismillah_pre,
  }));

  console.log('2/2  pages 1..604…');
  const verses = new Map(); // verse_key -> row
  const words = [];         // flat word rows
  for (let page = 1; page <= PAGES; page++) {
    const j = await fetchJson(
      `${API}/verses/by_page/${page}?words=true&word_fields=${WORD_FIELDS}&per_page=50`
    );
    if (!j.verses?.length) throw new Error(`page ${page}: empty response`);
    if (j.pagination?.total_pages > 1) {
      throw new Error(`page ${page}: paginated response, raise per_page`);
    }
    for (const v of j.verses) {
      const chapterId = parseInt(v.verse_key.split(':')[0], 10);
      if (!verses.has(v.verse_key)) {
        verses.set(v.verse_key, {
          verse_key: v.verse_key,
          chapter_id: chapterId,
          verse_number: v.verse_number,
          page: v.page_number ?? page,
          juz_number: v.juz_number,
          hizb_number: v.hizb_number,
          rub_el_hizb_number: v.rub_el_hizb_number,
          sajdah_number: v.sajdah_number ?? null,
        });
      }
      let pos = 0;
      for (const w of v.words ?? []) {
        if (w.char_type_name !== 'word') continue; // ayah-end glyphs are not stored
        pos += 1;
        words.push({
          location: w.location,
          verse_key: v.verse_key,
          page: w.v2_page,
          line_number: w.line_number,
          word_position: pos,
          code_v2: w.code_v2,
          text_uthmani: w.text_uthmani,
          v2_page: w.v2_page,
        });
      }
    }
    if (page % 50 === 0) console.log(`   …page ${page}`);
    await sleep(60); // be polite to the public API
  }

  // word locations must be unique across the whole mushaf
  const seen = new Set();
  for (const w of words) {
    if (seen.has(w.location)) throw new Error(`duplicate word location ${w.location}`);
    seen.add(w.location);
  }

  const L = [];
  L.push('-- quran_snapshot.sql · GENERATED by scripts/snapshot-quran.mjs — do not edit by hand');
  L.push(`-- generated at ${new Date().toISOString()} · source: ${API} · pages 1..604`);
  L.push('');
  L.push('-- chapters');
  for (const b of batches(chapters, 50)) {
    L.push('insert into public.chapters (id, name_arabic, name_simple, verses_count, bismillah_pre) values');
    L.push(
      b.map((c) => `  (${c.id}, ${sql(c.name_arabic)}, ${sql(c.name_simple)}, ${c.verses_count}, ${c.bismillah_pre})`).join(',\n') +
      '\non conflict (id) do nothing;'
    );
  }
  L.push('');
  L.push('-- quran_verses');
  for (const b of batches([...verses.values()], 200)) {
    L.push('insert into public.quran_verses (verse_key, chapter_id, verse_number, page, juz_number, hizb_number, rub_el_hizb_number, sajdah_number) values');
    L.push(
      b.map((v) => `  (${sql(v.verse_key)}, ${v.chapter_id}, ${v.verse_number}, ${v.page}, ${v.juz_number}, ${v.hizb_number}, ${v.rub_el_hizb_number}, ${num(v.sajdah_number)})`).join(',\n') +
      '\non conflict (verse_key) do nothing;'
    );
  }
  L.push('');
  L.push('-- quran_words');
  for (const b of batches(words, 400)) {
    L.push('insert into public.quran_words (location, verse_key, page, line_number, word_position, code_v2, text_uthmani, v2_page) values');
    L.push(
      b.map((w) => `  (${sql(w.location)}, ${sql(w.verse_key)}, ${w.page}, ${w.line_number}, ${w.word_position}, ${sql(w.code_v2)}, ${sql(w.text_uthmani)}, ${w.v2_page})`).join(',\n') +
      '\non conflict (location) do nothing;'
    );
  }
  L.push('');

  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, L.join('\n'), 'utf8');
  console.log(`DONE → ${outFile}`);
  console.log(`chapters=${chapters.length} verses=${verses.size} words=${words.length}`);
}

main().catch((e) => {
  console.error('FAILED:', e.message);
  process.exit(1);
});
